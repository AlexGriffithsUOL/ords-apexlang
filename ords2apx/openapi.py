"""OpenAPI 3.0 document for ORDS modules.

    ords2apx openapi rest/ --url https://host/ords/hr/ -o openapi.json

Paths come from module base paths and templates (`:id` becomes `{id}`),
parameters from URL binds and ORDS parameter components, and security from
privileges: a privilege protecting a module or URL pattern becomes an OAuth2
client-credentials requirement against the schema's /oauth/token endpoint.
"""

from __future__ import annotations

import fnmatch
import json
import re

from . import __version__
from .apx import Array, Component, Document, Reference, Text
from .restsource import _join, _text, slug

TYPES = {
    "STRING": {"type": "string"}, "INT": {"type": "integer"}, "LONG": {"type": "integer", "format": "int64"},
    "DOUBLE": {"type": "number"}, "BOOLEAN": {"type": "boolean"}, "TIMESTAMP": {"type": "string", "format": "date-time"},
}
ROW = {"type": "object", "additionalProperties": True}
COLLECTION = {
    "type": "object",
    "properties": {
        "items": {"type": "array", "items": ROW},
        "hasMore": {"type": "boolean"}, "limit": {"type": "integer"}, "offset": {"type": "integer"},
        "count": {"type": "integer"},
        "links": {"type": "array", "items": {"type": "object", "properties": {
            "rel": {"type": "string"}, "href": {"type": "string"}}}},
    },
}


def _names(c: Component, key: str) -> list[str]:
    v = c.get(key)
    if not isinstance(v, Array):
        return []
    return [i.target if isinstance(i, Reference) else i.value if isinstance(i, Text) else i.text for i in v.items]


def _response(source_type: str, method: str) -> dict:
    if source_type == "collection" or (source_type == "query" and method == "GET"):
        content = {"application/json": {"schema": COLLECTION}}
    elif source_type in ("item", "queryOneRow"):
        content = {"application/json": {"schema": ROW}}
    elif source_type == "csvQuery":
        content = {"text/csv": {"schema": {"type": "string"}}}
    elif source_type == "media":
        content = {"application/octet-stream": {"schema": {"type": "string", "format": "binary"}}}
    else:
        content = {"application/json": {"schema": ROW}}
    return {"description": "Success", "content": content}


def generate(docs: list[Document], url: str, title: str | None = None) -> dict:
    components = [c for d in docs for c in d.components]
    modules = [c for c in components if c.kind == "restModule"]
    privileges = [c for c in components if c.kind == "restPrivilege"]
    spec: dict = {
        "openapi": "3.0.3",
        "info": {"title": title or "ORDS REST API", "version": "1.0.0",
                 "description": f"Generated by ords2apx {__version__} from ORDS modules: "
                                + ", ".join(m.id or "" for m in modules)},
        "servers": [{"url": url.rstrip("/")}],
        "paths": {},
        "tags": [{"name": m.id, **({"description": _text(m, "comments")} if _text(m, "comments") else {})}
                 for m in modules],
    }
    scopes: dict[str, str] = {}

    def protecting(module: Component, path: str) -> list[str]:
        out = []
        for p in privileges:
            sample = re.sub(r"\{[^}]+\}", "x", path)
            if module.id in _names(p, "modules") or any(fnmatch.fnmatchcase(sample, pat) for pat in _names(p, "patterns")):
                out.append(p.id)
                scopes[p.id] = _text(p, "label") or _text(p, "description") or p.id
        return out

    for module in modules:
        base = _text(module, "basePath") or "/"
        for template in (c for c in module.children if c.kind == "template"):
            pattern = template.id or ""
            path = _join(base, pattern)
            if not pattern.endswith("/"):
                path = path.rstrip("/")
            binds = re.findall(r":(\w+)", pattern)
            path = re.sub(r":(\w+)", r"{\1}", path)
            item: dict = {}
            if binds:
                item["parameters"] = [{"name": b, "in": "path", "required": True, "schema": {"type": "string"}}
                                      for b in binds]
            for handler in (c for c in template.children if c.kind == "handler"):
                method = (handler.id or "GET").upper()
                source_type = _text(handler, "type", "source") or "collection"
                op: dict = {
                    "tags": [module.id],
                    "operationId": slug(f"{module.id}-{method}-{pattern}").replace("-", "_"),
                    "responses": {"200": _response(source_type, method)},
                }
                summary = _text(handler, "comments") or _text(template, "comments")
                if summary:
                    op["summary"] = summary.split("\n")[0]
                params = []
                for p in (c for c in handler.children if c.kind == "parameter"):
                    source = _text(p, "source") or "uri"
                    access = (_text(p, "accessMethod") or "in").lower()
                    if p.id in binds or access == "out" or source == "response":
                        continue
                    params.append({"name": p.id, "in": "header" if source == "header" else "query",
                                   "schema": TYPES.get((_text(p, "type") or "STRING").upper(), {"type": "string"})})
                if params:
                    op["parameters"] = params
                if method in ("POST", "PUT", "PATCH"):
                    mimes = [m.strip() for m in (_text(handler, "mimesAllowed") or "application/json").split(",") if m.strip()]
                    op["requestBody"] = {"content": {m: {"schema": ROW} for m in mimes}}
                guards = protecting(module, path)
                if guards:
                    op["security"] = [{"ords_oauth2": guards}]
                    op["responses"]["401"] = {"description": "Not authorized"}
                item[method.lower()] = op
            if any(k in item for k in ("get", "post", "put", "delete", "patch")):
                spec["paths"][path] = item
    if scopes:
        spec["components"] = {"securitySchemes": {"ords_oauth2": {
            "type": "oauth2",
            "flows": {"clientCredentials": {"tokenUrl": url.rstrip("/") + "/oauth/token", "scopes": scopes}},
        }}}
    return spec


def dumps(spec: dict) -> str:
    return json.dumps(spec, indent=2) + "\n"
